#!/usr/bin/env python3
"""Assemble db/apply_all.sql from the numbered migrations.

The bundle exists because a deployment can be wired to a Supabase project this repo cannot reach
(the Vercel integration provisions one in its own account). Pasting one file into that project's SQL
editor is then the only route, and it must be the same schema the tests ran against, not a retyped copy.

Order matters: the RLS policies call app_current_user(), so the helper is defined before 0002 and then
replaced by the Supabase version that reads the JWT.
"""
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
PARTS = ["db/migrations/0001_init.sql", "db/policies/0002_rls.sql",
         "db/migrations/0003_supabase_auth.sql", "db/migrations/0004_workspace.sql"]

PREAMBLE = """-- Generated by scripts/gen_apply_all.py - do not edit by hand.
-- Paste the whole file into the Supabase SQL editor once, on an empty project.
-- Safe on a project that has none of these tables; not idempotent on one that already has them.

create extension if not exists pgcrypto;
create extension if not exists citext;

-- Placeholder so 0002's policies can reference the helper before 0003 redefines it to read the JWT.
create or replace function app_current_user() returns uuid
language sql stable as $$ select nullif(current_setting('app.user_id', true), '')::uuid; $$;
"""


def main() -> None:
    chunks = [PREAMBLE]
    for part in PARTS:
        chunks.append(f"\n\n-- ============================================================ {part}\n")
        chunks.append((ROOT / part).read_text())
    out = "\n".join(chunks).rstrip() + "\n"
    (ROOT / "db/apply_all.sql").write_text(out)
    print(f"db/apply_all.sql: {len(out.splitlines())} lines")


if __name__ == "__main__":
    main()
